#!/usr/bin/env bash
# Regenerates .agents/STATE.md: the short "where are we" page every session
# reads first (AUTONOMY.md). Built only from versioned state and GitHub, never
# from free text, so it cannot go stale beyond the last run.
#
# Usage:
#   scripts/state.sh            # writes .agents/STATE.md
#   scripts/state.sh --stdout   # prints it instead
#
# Sources: docs/roadmap.md (first unchecked phase), .agents/tasks.json, the
# last lines of .agents/progress.md, and GitHub through REST only (open PRs,
# open issues labelled needs-human). GraphQL is not used: it is blocked in
# cloud sessions. If GitHub cannot be read, the GitHub lines say so and the
# exit code is 2; the file is still written.
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
OUT="$ROOT/.agents/STATE.md"
TMP="$(mktemp)"
trap 'rm -f "$TMP"' EXIT

gh_ok=1
prs="$(gh api 'repos/{owner}/{repo}/pulls?state=open&per_page=100' 2>/dev/null)" || { prs='[]'; gh_ok=0; }
asks="$(gh api 'repos/{owner}/{repo}/issues?state=open&labels=needs-human&per_page=100' 2>/dev/null)" || { asks='[]'; gh_ok=0; }

PRS="$prs" ASKS="$asks" GH_OK="$gh_ok" python3 - "$ROOT" > "$TMP" <<'PY'
import json, os, re, sys

root = sys.argv[1]
roadmap = open(f"{root}/docs/roadmap.md").read()
tasks = json.load(open(f"{root}/.agents/tasks.json"))["tasks"]
progress = [l.rstrip() for l in open(f"{root}/.agents/progress.md") if re.match(r"\d{4}-\d\d-\d\d · ", l)]
gh_ok = os.environ["GH_OK"] == "1"
prs = json.loads(os.environ["PRS"])
asks = [i for i in json.loads(os.environ["ASKS"]) if "pull_request" not in i]

m = re.search(r"^- \[ \] \*\*(Phase (\d+)[^*]*)\*\*", roadmap, re.M)
phase_title, phase = (m.group(1), int(m.group(2))) if m else ("all phases done", None)

done = {t["id"] for t in tasks if t["status"] == "done"}
in_phase = [t for t in tasks if t.get("phase") == phase]
counts = {}
for t in in_phase:
    counts[t["status"]] = counts.get(t["status"], 0) + 1
active = [t for t in tasks if t["status"] in ("in_progress", "in_review")]
blocked = [t for t in tasks if t["status"] == "blocked"]
ready = [t for t in in_phase if t["status"] == "todo" and all(d in done for d in t.get("depends_on", []))]

def task_line(t):
    extra = f", PR #{t['pr']}" if t.get("pr") else ""
    return f"- {t['id']} {t['status']} — {t['title']} (`{t.get('branch') or '-'}`{extra})"

lines = [
    "# State",
    "",
    "Generated by `scripts/state.sh`; do not edit by hand. Policy: `AUTONOMY.md`.",
    "",
    f"- Phase: {phase_title}",
    "- Tasks in phase: " + (", ".join(f"{n} {s}" for s, n in sorted(counts.items())) or "none planned"),
    f"- Next ready: {ready[0]['id']} — {ready[0]['title']}" if ready else "- Next ready: none",
    "",
    "## Active",
    "",
]
lines += [task_line(t) for t in active] or ["- none"]
lines += [f"- {t['id']} blocked — {t.get('blocked_reason', '?')}" for t in blocked]
lines += ["", "## GitHub", ""]
if gh_ok:
    lines += [f"- PR #{p['number']} open{' (draft)' if p.get('draft') else ''} — {p['title']}" for p in prs] or ["- no open PRs"]
    lines += [f"- needs-human: #{i['number']} — {i['title']}" for i in asks] or ["- no needs-human issues"]
else:
    lines += ["- GitHub could not be read; PRs and needs-human issues unknown"]
lines += ["", "## Last events", ""]
lines += [f"- {l}" for l in progress[-3:]]
print("\n".join(lines))
PY
if [[ "${1:-}" == "--stdout" ]]; then cat "$TMP"; else cp "$TMP" "$OUT"; fi
[[ "$gh_ok" == 1 ]] || exit 2
